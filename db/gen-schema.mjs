// Generates db/schema.postgres.sql + db/schema.sqlite.sql from db/schema-dump.json
// (dump captured from the live Neon database via the temporary admin route).
// Usage: node ./db/gen-schema.mjs
import fs from 'node:fs';

// DDL for features added after the initial schema dump — keep in sync with
// PG_MIGRATIONS in src/lib/db.ts (Postgres applies it at runtime).
const MIGRATION_SQL = `
-- ==== migrations (also applied by src/lib/db.ts for Postgres) ====
CREATE TABLE IF NOT EXISTS email_outbox (
  id TEXT NOT NULL,
  business_id TEXT NOT NULL DEFAULT '',
  to_addr TEXT NOT NULL,
  subject TEXT NOT NULL DEFAULT '',
  body TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending',
  attempts INTEGER NOT NULL DEFAULT 0,
  last_error TEXT NOT NULL DEFAULT '',
  provider_id TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  sent_at TEXT,
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_outbox_status ON email_outbox (status, created_at);
`;

const dump = JSON.parse(fs.readFileSync(new URL('./schema-dump.json', import.meta.url), 'utf8'));
const { columns, pks, fks, uniques, indexes, sequences } = dump;

const byTable = new Map();
for (const c of columns) {
  if (!byTable.has(c.table_name)) byTable.set(c.table_name, []);
  byTable.get(c.table_name).push(c);
}
const pkCols = (t) => pks.filter((p) => p.table_name === t).map((p) => p.column_name);
const fkList = (t) => fks.filter((f) => f.table_name === t);
const uniqList = (t) => uniques.filter((u) => u.table_name === t);

// ---- type maps ----
const sqliteType = {
  text: 'TEXT', varchar: 'TEXT', bpchar: 'TEXT', char: 'TEXT', uuid: 'TEXT', citext: 'TEXT', name: 'TEXT', inet: 'TEXT',
  int2: 'INTEGER', int4: 'INTEGER', int8: 'INTEGER', oid: 'INTEGER', serial: 'INTEGER',
  bool: 'INTEGER',
  float4: 'REAL', float8: 'REAL',
  numeric: 'NUMERIC', money: 'NUMERIC',
  timestamptz: 'TEXT', timestamp: 'TEXT', date: 'TEXT', time: 'TEXT',
  jsonb: 'TEXT', json: 'TEXT',
  bytea: 'BLOB',
};

function sqliteDefault(col) {
  const d = col.column_default;
  if (!d) return '';
  if (/nextval\(/i.test(d)) return ''; // identity/serial — not used by app (ids are text uid())
  if (/gen_random_uuid/i.test(d)) return '';
  if (/now\(\)|CURRENT_TIMESTAMP/i.test(d)) {
    // Match Date.toISOString() exactly so mixed-format string comparisons stay correct.
    return ` DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))`;
  }
  if (col.data_type === 'boolean') return ` DEFAULT ${d === 'true' ? 1 : d === 'false' ? 0 : d}`;
  // Strip pg casts (e.g. '[]'::text → '[]') — SQLite does not accept ::type syntax.
  return ` DEFAULT ${d.replace(/::[a-z ]+(\[\])?/g, '').trim()}`;
}

function pgType(c) {
  // udt_name values are valid pg type names (text, varchar, int4, timestamptz, jsonb, ...)
  if (c.data_type === 'ARRAY') return `${c.udt_name}[]`;
  return c.udt_name;
}

function pgDefault(c) {
  const d = c.column_default;
  if (!d) return '';
  return ` DEFAULT ${d}`;
}

// ---- Postgres ----
let pg = `-- LeadPilot schema (Postgres) — regenerated from live Neon dump\n-- Generated by db/gen-schema.mjs. Run with: node ./db/migrate-pg.mjs\n`;
for (const s of sequences) pg += `CREATE SEQUENCE IF NOT EXISTS ${s.sequence_name};\n`;
pg += '\n';
for (const [t, cols] of [...byTable.entries()].sort()) {
  const lines = [];
  for (const c of cols.sort((a, b) => a.ordinal_position - b.ordinal_position)) {
    let line = `  ${c.column_name} ${pgType(c)}`;
    if (c.is_nullable === 'NO') line += ' NOT NULL';
    line += pgDefault(c);
    lines.push(line);
  }
  const pk = pkCols(t);
  if (pk.length) lines.push(`  PRIMARY KEY (${pk.join(', ')})`);
  for (const u of uniqList(t)) lines.push(`  UNIQUE (${u.cols})`);
  for (const f of fkList(t)) {
    const rule = f.delete_rule && f.delete_rule !== 'NO ACTION' ? ` ON DELETE ${f.delete_rule}` : '';
    lines.push(`  FOREIGN KEY (${f.column_name}) REFERENCES ${f.ref_table} (${f.ref_column})${rule}`);
  }
  pg += `CREATE TABLE IF NOT EXISTS ${t} (\n${lines.join(',\n')}\n);\n`;
}
pg += '\n';
for (const i of indexes) {
  let stmt = i.indexdef.replace(/ ON public\./, ' ON ').replace(/^CREATE (UNIQUE )?INDEX /, 'CREATE $1INDEX IF NOT EXISTS ');
  pg += `${stmt};\n`;
}

// ---- SQLite ----
let lite = `-- LeadPilot schema (SQLite / local dev)\n-- Generated by db/gen-schema.mjs from the live Postgres dump.\n-- Executed automatically by src/lib/db.ts on first run.\n`;
for (const [t, cols] of [...byTable.entries()].sort()) {
  const lines = [];
  for (const c of cols.sort((a, b) => a.ordinal_position - b.ordinal_position)) {
    const type = sqliteType[c.udt_name] ?? (c.data_type === 'ARRAY' ? 'TEXT' : c.udt_name.toUpperCase());
    let line = `  ${c.column_name} ${type}`;
    if (c.is_nullable === 'NO') line += ' NOT NULL';
    line += sqliteDefault(c);
    lines.push(line);
  }
  const pk = pkCols(t);
  if (pk.length) lines.push(`  PRIMARY KEY (${pk.join(', ')})`);
  for (const u of uniqList(t)) lines.push(`  UNIQUE (${u.cols})`);
  for (const f of fkList(t)) {
    const rule = f.delete_rule && f.delete_rule !== 'NO ACTION' ? ` ON DELETE ${f.delete_rule}` : '';
    lines.push(`  FOREIGN KEY (${f.column_name}) REFERENCES ${f.ref_table} (${f.ref_column})${rule}`);
  }
  lite += `CREATE TABLE IF NOT EXISTS ${t} (\n${lines.join(',\n')}\n);\n`;
}
lite += '\n';
for (const i of indexes) {
  const stmt = i.indexdef
    .replace(/ ON public\./, ' ON ')
    .replace(/^CREATE (UNIQUE )?INDEX /, 'CREATE $1INDEX IF NOT EXISTS ')
    .replace(/ USING btree/g, '')
    .replace(/::[a-z ]+(\[\])?/g, '') // strip pg casts (e.g. lower((email)::text))
    .replace(/\|\| /g, '|| ');
  lite += `${stmt};\n`;
}

fs.writeFileSync(new URL('./schema.postgres.sql', import.meta.url), pg + MIGRATION_SQL);
fs.writeFileSync(new URL('./schema.sqlite.sql', import.meta.url), lite + MIGRATION_SQL);
console.log(`tables: ${byTable.size} | pg statements written | sqlite statements written`);
console.log([...byTable.keys()].sort().join(', '));
